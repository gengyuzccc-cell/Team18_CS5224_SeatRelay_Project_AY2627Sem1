"""Render interview records, research summaries, TeX macros and speaking notes from validated data."""
from study import ORIGIN


def tex_macros(summary):
    sr, ctrl = (summary["conditions"][c] for c in ("SR", "CTRL"))
    interview = summary["interview_scenario"]
    values = {
        "SimInterviewN": summary["interview_profiles"],
        "SimInterviewStudents": summary["student_interview_profiles"],
        "SimInterviewOrganisers": summary["organiser_interview_profiles"],
        "SimStudyN": summary["study_profiles"],
        "SimStudyParticipantN": summary["participant_track"],
        "SimStudyOrganiserN": summary["organiser_track"],
        "SimTaskAttempts": summary["task_attempts"],
        "SimSusForms": summary["sus_forms"],
        "SimCompletionSR": sr["completion_pct"],
        "SimCompletionCtrl": ctrl["completion_pct"],
        "SimSusSR": sr["sus_mean"],
        "SimSusCtrl": ctrl["sus_mean"],
        "SimTotalTimeSR": sr["median_subject_total_s"],
        "SimTotalTimeCtrl": ctrl["median_subject_total_s"],
        "SimPairedReduction": summary["paired_subject_median_reduction_pct"],
        "SimFasterProfiles": summary["sr_faster_profiles"],
        "SimStepsSR": sr["median_organiser_steps"],
        "SimStepsCtrl": ctrl["median_organiser_steps"],
        "SimErrorsSR": sr["errors"],
        "SimErrorsCtrl": ctrl["errors"],
        "SimHelpSR": sr["help_requests"],
        "SimHelpCtrl": ctrl["help_requests"],
        "SimMultiSessionPct": interview["event_weighted_multi_session_pct"],
        "SimCoordinationHours": interview["baseline_coordination_hours_median"],
        "SimBargainSgd": interview["bargain_sgd_month_median"],
        "SimExpensiveSgd": interview["expensive_sgd_month_median"],
        "SimServiceablePct": interview["open_procurement_pct"],
        "SimAdoptionPct": 100 * interview["adoption_share_assumed"],
    }
    lines = [
        "% Generated by tools/research/simulate.py from results/research/summary.json.",
        "% SIMULATED research; 12 participants in the scenario. Real Study*/Interview* macros are not overwritten.",
    ]
    for key, value in values.items():
        formatted = f"{value:.1f}" if isinstance(value, float) else str(value)
        lines.append(f"\\newcommand{{\\{key}}}{{{formatted}}}")
    return "\n".join(lines) + "\n"


